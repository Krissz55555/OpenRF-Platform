#pragma once

// OpenRF Platform v1 reference wiring: ESP8266 NodeMCU V2 + CC1101
// SPI pins are the ESP8266 hardware SPI pins.
//
// CC1101 VCC  -> 3V3 (never 5 V)
// CC1101 GND  -> GND
// CC1101 SCK  -> D5 / GPIO14
// CC1101 MISO -> D6 / GPIO12
// CC1101 MOSI -> D7 / GPIO13
// CC1101 CSN  -> D8 / GPIO15
// CC1101 GDO0 -> D2 / GPIO4
// CC1101 GDO2 -> D1 / GPIO5

#define OPENRF_CC1101_CS_PIN D8
#define OPENRF_CC1101_GDO0_PIN D2
#define OPENRF_CC1101_GDO2_PIN D1

#define OPENRF_RADIO_FREQUENCY_MHZ 433.92F
#define OPENRF_RADIO_BIT_RATE_KBPS 4.8F
#define OPENRF_RADIO_FREQUENCY_DEVIATION_KHZ 5.0F
#define OPENRF_RADIO_RX_BANDWIDTH_KHZ 325.0F
#define OPENRF_RADIO_OUTPUT_POWER_DBM 10
#define OPENRF_RADIO_PREAMBLE_BITS 16
